export type TransferSource = 'codex' | 'commandcode' | 'antigravity' | 'claudeCode' | 'opencode' | 'zcode' | 'geminiCli';
export type TransferEvent = {
  eventId: string;
  source: TransferSource;
  sessionId: string;
  timestampMs: number;
  modelName: string;
  projectKey: string;
  projectName: string;
  workspacePath?: string;
  sessionTitle?: string;
  inputTokens: number;
  outputTokens: number;
  cacheReadTokens: number;
  cacheCreationTokens: number;
  reasoningTokens: number;
  recordedCost?: number;
};
export type TransferPrice = { inputPerMillion: number; outputPerMillion: number; cacheReadPerMillion?: number; cacheWritePerMillion?: number };
export type TransferBundle = {
  format: 'incept-token-transfer';
  version: 1;
  exportId: string;
  device: { id: string; label: string; platform: string };
  exportedAt: string;
  events: TransferEvent[];
  prices: Record<string, TransferPrice>;
  warnings: string[];
  checksum: string;
};
export type ImportMappings = Record<string, string | null>;
export type ImportProject = { key: string; name: string; path?: string; records: number; suggestedTarget?: string };
export type ImportPreview = {
  previewId: string;
  expiresAt: string;
  device: TransferBundle['device'];
  exportedAt: string;
  received: number;
  added: number;
  duplicateLocal: number;
  duplicateImported: number;
  conflicts: number;
  addedTokens: number;
  projects: ImportProject[];
  targets: Array<{ key: string; name: string; path?: string }>;
  models: Array<{ name: string; resolvedName: string; records: number; priced: boolean }>;
  warnings: string[];
};
export type ImportReceipt = {
  id: string;
  deviceId: string;
  deviceLabel: string;
  exportId: string;
  checksum: string;
  importedAt: string;
  status: 'active' | 'rolled_back';
  rolledBackAt?: string;
  received: number;
  added: number;
  duplicateLocal: number;
  duplicateImported: number;
  addedTokens: number;
};
